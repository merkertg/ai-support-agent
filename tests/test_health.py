"""Проверяем HTTP-ответ API без запуска отдельного сервера Uvicorn."""

# TestClient позволяет отправлять запросы приложению внутри теста.
from fastapi.testclient import TestClient

# Берём тот же объект приложения, который Uvicorn использует при запуске.
from app.main import app


def test_health() -> None:
    """Убедиться, что GET /health возвращает код 200 и ожидаемый JSON.

    Pytest находит функцию по префиксу test_ и выполняет её.
    Тест ничего не возвращает, поэтому указан тип None.
    Если условие assert ложно, Pytest отмечает тест как упавший.
    """
    # with открывает тестовый клиент и гарантирует его закрытие после блока.
    # Сетевой порт не используется: запрос идёт непосредственно в приложение.
    with TestClient(app) as client:
        # Вызываем обработчик GET /health и сохраняем HTTP-ответ.
        response = client.get("/health")

    # После закрытия клиента сохранённый ответ по-прежнему доступен.
    # Сначала проверяем HTTP-статус: 200 означает успешную обработку запроса.
    assert response.status_code == 200
    # json() разбирает JSON-ответ и возвращает обычный словарь Python.
    # Проверяем весь словарь, чтобы заметить изменение любого поля.
    assert response.json() == {
        "status": "ok",
        "service": "ai-support-agent",
    }
