"""Предсказуемые ошибки провайдера без содержимого запросов, ключей и ответов."""


class LLMError(Exception):
    """Описать безопасный HTTP-статус и публичный текст ожидаемой ошибки."""

    status_code = 503
    detail = "Сервис подготовки черновика временно недоступен."

    def __init__(self) -> None:
        """Не принимать исходную ошибку SDK, которая может содержать секреты."""
        super().__init__(self.detail)


class LLMConfigurationError(LLMError):
    """Сообщить об отсутствующей или неверной конфигурации без её значений."""

    status_code = 503
    detail = "Проверьте настройки LLM: провайдер, ключ, модель и ограничения."


class LLMUnavailableError(LLMError):
    """Сообщить о сетевой ошибке, ограничении запросов или сбое провайдера."""

    status_code = 503
    detail = "Провайдер LLM временно недоступен. Повторите запрос позже."


class LLMTimeoutError(LLMError):
    """Сообщить, что провайдер не завершил запрос за установленное время."""

    status_code = 504
    detail = "Провайдер LLM не ответил за установленное время."


class LLMInvalidResponseError(LLMError):
    """Отклонить неполный ответ или ответ, не соответствующий строгой схеме."""

    status_code = 502
    detail = "Провайдер LLM вернул неполный или некорректный черновик."


class LLMRefusedError(LLMError):
    """Сообщить об отказе модели без публикации исходного текста провайдера."""

    status_code = 502
    detail = "Провайдер LLM отказался подготовить черновик."


class LLMInputTooLongError(LLMError):
    """Отклонить слишком длинный контекст до любого обращения к провайдеру."""

    status_code = 413
    detail = "Контекст обращения превышает допустимые 16000 символов."
