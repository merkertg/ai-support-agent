"""Безопасные ошибки агента: наружу не попадают транскрипт и ответы SDK."""

from app.llm.errors import LLMError


class AgentConfigurationError(LLMError):
    """Сообщить о неверных ограничениях до запуска модели и инструментов."""

    status_code = 503
    detail = "Проверьте ограничения агента: шаги, инструменты и время выполнения."


class AgentStepLimitError(LLMError):
    """Остановить агента, который не завершился за разрешённое число шагов."""

    status_code = 502
    detail = "Агент достиг ограничения числа шагов без готового черновика."


class AgentToolLimitError(LLMError):
    """Отклонить весь пакет, превышающий общий лимит вызовов инструментов."""

    status_code = 502
    detail = "Агент превысил допустимое число вызовов инструментов."


class AgentInvalidTurnError(LLMError):
    """Отклонить неоднозначный шаг или повторный идентификатор вызова."""

    status_code = 502
    detail = "Агент получил некорректную последовательность ответов модели."


class AgentContextTooLongError(LLMError):
    """Остановить цикл до отправки слишком большого полного транскрипта."""

    status_code = 413
    detail = "Контекст агента превышает допустимые 64000 символов."


class AgentTimeoutError(LLMError):
    """Прервать общий бюджет времени, включая модель и инструменты."""

    status_code = 504
    detail = "Агент не завершил обработку за установленное время."
